test("table: one tab stop; arrows, Home/End, PageUp/PageDown, Ctrl+Home/End move focus (roving tabindex)", async ({ page }) => {
  const g = grid(page, "table-products")
  const rows = bodyRows(g)
  await page.locator("#table-mode-single").focus()
  await page.keyboard.press("Tab") // Single → Multi? no: Single is last button, Tab enters the table
  await expect(rows.first()).toBeFocused()
  await expect(rows.first()).toHaveAttribute("tabindex", "-1")
  await page.keyboard.press("ArrowDown")
  await expect(rows.nth(1)).toBeFocused()
  await expect(rows.first()).not.toHaveAttribute("tabindex")
  await page.keyboard.press("ArrowUp")
  await page.keyboard.press("ArrowUp")
  await expect(g.locator('[data-slot="table-header-row"]')).toBeFocused()
  await page.keyboard.press("ArrowDown")
  // Cells: → enters the row's cells (selection cell first), ← goes back, Home/End inside the row.
  await page.keyboard.press("ArrowRight")
  await expect(rows.first().locator("[data-selection-cell]")).toBeFocused()
  await page.keyboard.press("ArrowRight")
  await expect(rows.first().getByRole("gridcell", { name: "Product 1" })).toBeFocused()
  await page.keyboard.press("ArrowDown") // same column, next row
  await expect(rows.nth(1).getByRole("gridcell", { name: "Product 2" })).toBeFocused()
  await page.keyboard.press("End")
  await expect(rows.nth(1).locator("[data-actions-cell]")).toBeFocused()
  await page.keyboard.press("Home")
  await expect(rows.nth(1).locator("[data-selection-cell]")).toBeFocused()
  await page.keyboard.press("Home")
  await expect(rows.nth(1)).toBeFocused()
  await page.keyboard.press("End") // on a row: last row
  await expect(rows.last()).toBeFocused()
  await page.keyboard.press("Home") // on a row: first body row
  await expect(rows.first()).toBeFocused()
  await page.keyboard.press("PageDown")
  await expect(rows.last()).toBeFocused()
  await page.keyboard.press("PageUp")
  await expect(rows.first()).toBeFocused()
  await page.keyboard.press("Control+End")
  await expect(rows.last()).toBeFocused()
  await page.keyboard.press("Control+Home")
  await expect(rows.first()).toBeFocused()
  // Tab leaves the table (to the growing button below), Shift+Tab comes back to the same row.
  await page.keyboard.press("ArrowDown")
  await page.keyboard.press("Tab")
  await expect(page.locator("#table-products [data-slot=table-growing]")).toBeFocused()
  await page.keyboard.press("Shift+Tab")
  await expect(rows.nth(1)).toBeFocused()
})

