  const colIndex = React.useContext(HeaderColIndex)
  const { registerColumn, unregisterColumn } = ctx
  const aiAction = React.isValidElement(action) && action.type === TableHeaderCellActionAI ? action : undefined
  const [focused, setFocused] = React.useState(false)
  React.useLayoutEffect(() => {
    registerColumn(index, { width, minWidth, importance, popinText, popinHidden, horizontalAlign, label: children, aiAction })
  }, [registerColumn, index, width, minWidth, importance, popinText, popinHidden, horizontalAlign, children, aiAction])
